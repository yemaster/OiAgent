use std::{ffi::OsStr, process::Command};

/// Background probes and pipe-based tasks must not allocate a Windows console.
/// Interactive terminals use portable_pty instead of this command builder.
pub fn background_command(program: impl AsRef<OsStr>) -> Command {
    let mut command = Command::new(program);
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        // CREATE_NO_WINDOW: redirects still work; no separate console is created.
        // https://learn.microsoft.com/windows/win32/procthread/process-creation-flags
        command.creation_flags(0x0800_0000);
    }
    // Keep stdin closed for unattended tools, which must never wait for input.
    command.stdin(std::process::Stdio::null());
    command
}

/// Agent invocations preserve argv boundaries. Windows npm shims are batch
/// scripts: invoke their Node entry point directly for both pipes and ConPTY.
pub fn agent_command(program: impl AsRef<std::path::Path>) -> Result<Command, String> {
    let (program, prefix) = agent_invocation(program.as_ref())?;
    let mut command = background_command(program);
    command.args(prefix);
    Ok(command)
}

pub fn agent_pty_command(
    program: impl AsRef<std::path::Path>,
) -> Result<portable_pty::CommandBuilder, String> {
    let (program, prefix) = agent_invocation(program.as_ref())?;
    let mut command = portable_pty::CommandBuilder::new(program);
    command.args(prefix);
    Ok(command)
}

fn agent_invocation(
    program: &std::path::Path,
) -> Result<(std::path::PathBuf, Vec<std::ffi::OsString>), String> {
    #[cfg(windows)]
    {
        let ext = program
            .extension()
            .and_then(|s| s.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        if matches!(ext.as_str(), "cmd" | "bat" | "ps1") {
            let script = npm_node_entry(program)?.ok_or(
                "无法安全解析此 Windows 启动脚本，请在 Agent 程序中选择原生 .exe 或 Node .js 入口",
            )?;
            return Ok((node_runtime(program)?, vec![script.into_os_string()]));
        }
        if matches!(ext.as_str(), "js" | "cjs" | "mjs") {
            return Ok((node_runtime(program)?, vec![program.as_os_str().into()]));
        }
    }
    Ok((program.to_owned(), vec![]))
}

#[cfg(windows)]
fn node_runtime(program: &std::path::Path) -> Result<std::path::PathBuf, String> {
    let local = program
        .parent()
        .unwrap_or(std::path::Path::new("."))
        .join("node.exe");
    if local.is_file() {
        return Ok(local);
    }
    crate::discovery::resolve("node.exe")
        .ok_or("找不到 Node.js，请安装 Node.js 或选择 Agent 原生可执行文件".into())
}

// Recognize the no-extra-options Node template generated by npm/cmd-shim.
// Unknown wrappers must not be guessed: they may set required env or arguments.
#[cfg(any(windows, test))]
fn npm_node_entry(program: &std::path::Path) -> Result<Option<std::path::PathBuf>, String> {
    let metadata = std::fs::metadata(program).map_err(|e| e.to_string())?;
    if metadata.len() > 64 * 1024 {
        return Ok(None);
    }
    let text = std::fs::read_to_string(program).map_err(|e| e.to_string())?;
    if !text.contains("SET dp0=%~dp0") || !text.contains("SET \"_prog=node\"") {
        return Ok(None);
    }
    let invocation = "endLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & set PATHEXT=%PATHEXT:;.JS;=;% & \"%_prog%\"";
    let header = [
        "",
        "@ECHO off",
        "GOTO start",
        ":find_dp0",
        "SET dp0=%~dp0",
        "EXIT /b",
        ":start",
        "SETLOCAL",
        "CALL :find_dp0",
        "IF EXIST \"%dp0%\\node.exe\" (",
        "SET \"_prog=%dp0%\\node.exe\"",
        ") ELSE (",
        "SET \"_prog=node\"",
        ")",
    ];
    if text.lines().any(|line| {
        let line = line.trim();
        !header.contains(&line) && !line.starts_with(invocation)
    }) || text
        .lines()
        .filter(|line| line.trim().starts_with(invocation))
        .count()
        != 1
    {
        return Ok(None);
    }
    for line in text.lines() {
        let Some((_, tail)) = line.split_once("\"%_prog%\"") else {
            continue;
        };
        let tail = tail.trim();
        let Some(tail) = tail.strip_prefix("\"%dp0%\\") else {
            continue;
        };
        let Some((relative, suffix)) = tail.split_once('"') else {
            continue;
        };
        if suffix.trim() != "%*" || relative.contains(['%', '\0']) {
            continue;
        }
        let path = program
            .parent()
            .unwrap_or(std::path::Path::new("."))
            .join(relative.replace('\\', "/"));
        if !matches!(
            path.extension().and_then(|s| s.to_str()),
            Some("js" | "cjs" | "mjs")
        ) {
            continue;
        }
        if !path.is_file() {
            return Err("Agent 启动脚本对应的 Node 入口不存在，请重新安装该程序".into());
        }
        return Ok(Some(path));
    }
    Ok(None)
}

/// Stop the task process and its subprocesses, including Windows command shims.
pub fn terminate_background(child: &mut std::process::Child) {
    if child.try_wait().ok().flatten().is_some() {
        return;
    }
    #[cfg(unix)]
    unsafe {
        libc::kill(-(child.id() as i32), libc::SIGKILL);
    }
    #[cfg(windows)]
    terminate_windows_tree(child.id());
    let _ = child.kill();
}

#[cfg(windows)]
pub fn terminate_windows_tree(pid: u32) {
    use std::{
        process::Stdio,
        time::{Duration, Instant},
    };
    let Some(root) = std::env::var_os("SystemRoot") else {
        return;
    };
    let program = std::path::PathBuf::from(root)
        .join("System32")
        .join("taskkill.exe");
    let Ok(mut killer) = background_command(program)
        .args(["/PID", &pid.to_string(), "/T", "/F"])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
    else {
        return;
    };
    let start = Instant::now();
    loop {
        match killer.try_wait() {
            Ok(Some(_)) => break,
            _ if start.elapsed() > Duration::from_secs(5) => {
                let _ = killer.kill();
                let _ = killer.wait();
                break;
            }
            Err(_) => {
                let _ = killer.kill();
                let _ = killer.wait();
                break;
            }
            _ => std::thread::sleep(Duration::from_millis(20)),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Stdio;

    #[test]
    fn background_command_preserves_output_and_exit_status() {
        // Spawn this test executable so the regression is independent of any
        // installed shell, Git, or Agent. The Windows child checks its console.
        let output = background_command(std::env::current_exe().unwrap())
            .args([
                "--exact",
                "process::tests::child_process_probe",
                "--nocapture",
            ])
            .env("OIAGENT_BACKGROUND_PROCESS_PROBE", "1")
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .output()
            .unwrap();
        assert_eq!(output.status.code(), Some(7), "{output:?}");
        assert!(String::from_utf8_lossy(&output.stdout).contains("background stdout"));
        assert!(String::from_utf8_lossy(&output.stderr).contains("background stderr"));
    }

    #[test]
    fn child_process_probe() {
        if std::env::var("OIAGENT_BACKGROUND_PROCESS_PROBE").as_deref() != Ok("1") {
            return;
        }
        #[cfg(windows)]
        {
            #[link(name = "kernel32")]
            extern "system" {
                fn GetConsoleWindow() -> *mut std::ffi::c_void;
            }
            assert!(
                unsafe { GetConsoleWindow() }.is_null(),
                "background process allocated a console"
            );
        }
        println!("background stdout");
        eprintln!("background stderr");
        std::process::exit(7);
    }
}

#[cfg(test)]
mod argv_tests {
    use super::*;
    use std::{
        io::{BufRead, BufReader},
        path::Path,
    };

    fn payload() -> Vec<String> {
        [
            "",
            "two words",
            "中文路径",
            r#"{"model":{"name":"custom model","depth":"high"}}"#,
            r#"model_reasoning_effort="high""#,
            "quotes \" and ' apostrophe",
            r"C:\Project Files\",
            "%PATH% !PATH! & echo NOT_A_COMMAND | < > ^",
            "$(echo NOT_A_COMMAND)`echo nope`",
            "line1\nline2",
            "--not-an-option",
        ]
        .map(String::from)
        .to_vec()
    }
    fn echo_script(root: &Path) -> std::path::PathBuf {
        let script = root.join("node_modules/agent with spaces/cli.js");
        std::fs::create_dir_all(script.parent().unwrap()).unwrap();
        std::fs::write(
            &script,
            "process.stdout.write('ARGV_RESULT='+JSON.stringify(process.argv.slice(2))+'\\n');",
        )
        .unwrap();
        script
    }
    fn shim(root: &Path) -> std::path::PathBuf {
        let path = root.join("agent.cmd");
        // npm/cmd-shim's no-extra-options Node wrapper.
        std::fs::write(&path, "@ECHO off\r\nSET dp0=%~dp0\r\nIF EXIST \"%dp0%\\node.exe\" (\r\n SET \"_prog=%dp0%\\node.exe\"\r\n) ELSE (\r\n SET \"_prog=node\"\r\n)\r\nendLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & set PATHEXT=%PATHEXT:;.JS;=;% & \"%_prog%\"  \"%dp0%\\node_modules\\agent with spaces\\cli.js\" %*\r\n").unwrap();
        path
    }
    fn assert_output(output: &[u8]) {
        let text = String::from_utf8_lossy(output);
        let json = text.split("ARGV_RESULT=").nth(1).expect(&text);
        let value = serde_json::Deserializer::from_str(json)
            .into_iter::<Vec<String>>()
            .next()
            .unwrap()
            .unwrap();
        assert_eq!(value, payload());
    }
    fn pty_output(command: portable_pty::CommandBuilder) -> Vec<u8> {
        let pair = portable_pty::native_pty_system()
            .openpty(portable_pty::PtySize {
                rows: 24,
                cols: 4096,
                pixel_width: 0,
                pixel_height: 0,
            })
            .unwrap();
        let mut child = pair.slave.spawn_command(command).unwrap();
        drop(pair.slave);
        let reader = pair.master.try_clone_reader().unwrap();
        let (send, receive) = std::sync::mpsc::channel();
        std::thread::spawn(move || {
            // ConPTY can keep the pipe open until the console closes. Wait for
            // the complete result record, not EOF, and bound the wait below.
            let mut reader = BufReader::new(reader);
            let mut output = String::new();
            loop {
                let mut line = String::new();
                if !matches!(reader.read_line(&mut line), Ok(n) if n > 0) {
                    break;
                }
                output.push_str(&line);
                if let Some(json) = output.split("ARGV_RESULT=").nth(1) {
                    if matches!(
                        serde_json::Deserializer::from_str(json)
                            .into_iter::<Vec<String>>()
                            .next(),
                        Some(Ok(_))
                    ) {
                        break;
                    }
                }
            }
            let _ = send.send(output.into_bytes());
        });
        let output = receive.recv_timeout(std::time::Duration::from_secs(10));
        if output.is_err() {
            let _ = child.kill();
        }
        let status = child.wait().unwrap();
        drop(pair.master);
        let output = output.expect("PTY argument probe timed out");
        assert!(status.success());
        output
    }
    #[test]
    fn npm_shim_entry_preserves_path_and_rejects_unrecognized_options() {
        let root = tempfile::Builder::new()
            .prefix("oiagent argv 中文 ")
            .tempdir()
            .unwrap();
        let script = echo_script(root.path());
        let wrapper = shim(root.path());
        assert_eq!(npm_node_entry(&wrapper).unwrap(), Some(script));
        let text = std::fs::read_to_string(&wrapper).unwrap();
        std::fs::write(
            &wrapper,
            text.replace("\"%_prog%\"  ", "\"%_prog%\" --unknown "),
        )
        .unwrap();
        assert_eq!(npm_node_entry(&wrapper).unwrap(), None);
        std::fs::write(&wrapper, format!("SET NODE_OPTIONS=--custom\n{text}")).unwrap();
        assert_eq!(npm_node_entry(&wrapper).unwrap(), None);
    }
    #[test]
    fn native_and_pty_argv_round_trip_without_shell_expansion() {
        let root = tempfile::Builder::new()
            .prefix("oiagent argv 中文 ")
            .tempdir()
            .unwrap();
        let script = echo_script(root.path());
        let node = crate::discovery::resolve(if cfg!(windows) { "node.exe" } else { "node" })
            .expect("Node.js is required for argv integration tests");
        let output = agent_command(&node)
            .unwrap()
            .arg(&script)
            .args(payload())
            .output()
            .unwrap();
        assert!(output.status.success());
        assert_output(&output.stdout);
        let mut command = agent_pty_command(&node).unwrap();
        command.arg(&script);
        command.args(payload());
        assert_output(&pty_output(command));
    }
    #[cfg(windows)]
    #[test]
    fn windows_npm_shim_round_trips_json_and_metacharacters_in_both_modes() {
        let root = tempfile::Builder::new()
            .prefix("oiagent argv 中文 ")
            .tempdir()
            .unwrap();
        echo_script(root.path());
        let wrapper = shim(root.path());
        let output = agent_command(&wrapper)
            .unwrap()
            .args(payload())
            .output()
            .unwrap();
        assert!(output.status.success());
        assert_output(&output.stdout);
        let mut command = agent_pty_command(&wrapper).unwrap();
        command.args(payload());
        assert_output(&pty_output(command));
    }
}
